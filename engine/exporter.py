"""Build a portable, machine-independent release archive."""
from __future__ import annotations

import hashlib
import json
import os
import shutil
import subprocess
import sys
import tarfile
import tempfile
from datetime import datetime, timezone
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
    from engine import utilities as u
else:
    from . import utilities as u

VERSION = "1.1.2"
INCLUDE = [
    "README.md", "docs",
    "install.sh", "uninstall.sh", "verify.sh", "repair.sh", "export.sh",
    "tahoe.sh",
    "config", "manifests", "engine", "scripts", "extensions", "assets",
    "tools", "tests",
]
EXCLUDE_NAMES = {".git", "__pycache__", "*.pyc", "runtime", "state", "backups",
                 "logs", "releases"}


PROPRIETARY_PATHS = ("assets/references", "assets/wallpapers/apple")
# Reports describing this machine are regenerated by the installer.
MACHINE_REPORTS = (
    "docs/reports/INITIAL_AUDIT.md",
    "docs/reports/COMPATIBILITY_REPORT.md",
    "docs/reports/INSTALLATION_REPORT.md",
    "docs/reports/PERFORMANCE_SAMPLE.md",
)


def _filter(path: Path, root: Path, include_proprietary: bool = False) -> bool:
    rel = path.relative_to(root)
    rel_posix = rel.as_posix()
    parts = set(rel.parts)
    if parts & EXCLUDE_NAMES:
        return False
    if path.name.endswith(".pyc") or path.name == "__pycache__":
        return False
    if not include_proprietary:
        if any(rel_posix == p or rel_posix.startswith(p + "/")
               for p in PROPRIETARY_PATHS):
            return False
    if rel_posix in MACHINE_REPORTS:
        return False
    return True


def _collect(root: Path, include_proprietary: bool = False) -> list[Path]:
    files: list[Path] = []
    for entry in INCLUDE:
        path = root / entry
        if not path.exists():
            continue
        if path.is_file():
            files.append(path)
        else:
            for child in sorted(path.rglob("*")):
                if child.is_file() and _filter(child, root, include_proprietary):
                    files.append(child)
    return files


def _ensure_executables(root: Path) -> None:
    for name in ("install.sh", "uninstall.sh", "verify.sh", "repair.sh", "export.sh"):
        path = root / name
        if path.exists():
            path.chmod(0o755)


def export(root: Path, output: Path | None = None,
           include_proprietary: bool = False) -> dict:
    root = Path(root)
    output = Path(output or (root / "releases"))
    output.mkdir(parents=True, exist_ok=True)
    name = f"macos-tahoe-ubuntu-v{VERSION}"
    archive = output / f"{name}.tar.gz"
    checksum_file = output / f"{name}.sha256"
    manifest_file = output / f"{name}-manifest.json"
    tmp_parent = Path(tempfile.mkdtemp(prefix="tahoe-release-"))
    staging = tmp_parent / name
    staging.mkdir()

    files = _collect(root, include_proprietary)
    for source in files:
        rel = source.relative_to(root)
        target = staging / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target, follow_symlinks=True)
    _ensure_executables(staging)

    # Sanity checks: nothing machine-specific may leak into a release.
    forbidden = [p for p in staging.rglob("*")
                 if p.is_dir() and p.name in {"backups", "state", "logs", "runtime"}]
    if forbidden:
        raise u.EngineError("refusing to export machine-specific directories: "
                            + ", ".join(str(p) for p in forbidden))
    required = ["install.sh", "engine/main.py", "config/desktop.json",
                "manifests/components.lock.json", "assets/wallpapers/tahoe-dark.png",
                "extensions/tpct-mac-shell@tpct/metadata.json"]
    missing = [r for r in required if not (staging / r).exists()]
    if missing:
        raise u.EngineError("release is missing required files: " + ", ".join(missing))

    # Byte-compile the engine to catch syntax errors without running it.
    for py in (staging / "engine").glob("*.py"):
        proc = subprocess.run([sys.executable, "-m", "py_compile", str(py)],
                              capture_output=True, text=True)
        if proc.returncode != 0:
            raise u.EngineError(f"engine syntax error in {py.name}: {proc.stderr}")
    for cache in (staging / "engine").rglob("__pycache__"):
        shutil.rmtree(cache, ignore_errors=True)

    with tarfile.open(archive, "w:gz") as tf:
        tf.add(staging, arcname=name)
    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    checksum_file.write_text(f"{digest}  {archive.name}\n", encoding="utf-8")

    manifest = {
        "name": name,
        "version": VERSION,
        "created_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "archive": archive.name,
        "sha256": digest,
        "size_bytes": archive.stat().st_size,
        "source_commit": _git_commit(root),
        "contents": sorted(str(p.relative_to(staging)) for p in staging.rglob("*")
                           if p.is_file()),
        "excludes": ["state/", "backups/", "logs/", "runtime/", ".git/",
                     "reports/final-performance.json",
                     "assets/references/ (Apple screenshots, proprietary)",
                     "assets/wallpapers/apple/ (Apple wallpapers, proprietary)"]
                     if not include_proprietary else
                     ["state/", "backups/", "logs/", "runtime/", ".git/"],
        "restore_instructions": [
            f"Copy {archive.name} and {checksum_file.name} to external storage.",
            "On the fresh Ubuntu machine: tar xzf " + archive.name,
            f"cd {name} && sha256sum -c ../{checksum_file.name}",
            "./install.sh",
        ],
    }
    manifest_file.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    shutil.rmtree(tmp_parent, ignore_errors=True)
    return {"archive": archive, "sha256": checksum_file, "manifest": manifest_file,
            "digest": digest, "size_bytes": archive.stat().st_size,
            "file_count": len(manifest["contents"])}


def _git_commit(root: Path) -> str | None:
    try:
        proc = subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD"],
                              capture_output=True, text=True, timeout=15)
        return proc.stdout.strip() if proc.returncode == 0 else None
    except (OSError, subprocess.TimeoutExpired):
        return None


def main(argv: list[str] | None = None) -> int:
    import argparse
    parser = argparse.ArgumentParser(description="Export a portable release.")
    parser.add_argument("--output", type=Path, help="output directory")
    parser.add_argument("--include-proprietary", action="store_true",
                        help="include Apple wallpapers/screenshots (personal use only)")
    args = parser.parse_args(argv)
    root = Path(__file__).resolve().parent.parent
    result = export(root, args.output, include_proprietary=args.include_proprietary)
    print(f"release:   {result['archive']}")
    print(f"sha256:    {result['digest']}")
    print(f"checksum:  {result['sha256']}")
    print(f"manifest:  {result['manifest']}")
    print(f"files:     {result['file_count']}")
    print()
    print("Copy the .tar.gz and .sha256 files to external storage BEFORE reinstalling Ubuntu.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
