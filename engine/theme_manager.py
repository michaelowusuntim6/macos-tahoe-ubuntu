"""Install themes, icons, cursors, fonts, wallpapers and app-level styling."""
from __future__ import annotations

import logging
import shutil
import tempfile
from pathlib import Path

from . import utilities as u

log = logging.getLogger("engine")

GTK_MARKER = "/* tpct-mac-theme */"
GTK3_BEGIN = "/* macos-tahoe-ubuntu: begin */"
GTK3_END = "/* macos-tahoe-ubuntu: end */"
FIREFOX_MARK = "// macos-tahoe-ubuntu begin"


def _home() -> Path:
    return Path.home()


def _install_tree(src: Path, dest: Path, *, dry_run: bool) -> None:
    if dry_run:
        log.info("[dry-run] would install %s -> %s", src, dest)
        return
    u.copy_tree_atomic(src, dest)


def theme_assets_present(root: Path) -> bool:
    base = root / "assets/themes/tpct-dist"
    return all((base / f"TPCT-Mac-{v}" / "gnome-shell/gnome-shell.css").exists()
               for v in ("Dark", "Light"))


def build_theme_from_source(root: Path) -> bool:
    source = root / "assets/themes/tpct-src"
    sassc = shutil.which("sassc")
    if not sassc:
        return False
    log.info("rebuilding theme from SCSS source")
    env = dict(**__import__("os").environ)
    u.run(["bash", str(source / "build.sh")], timeout=300, cwd=source, env=env)
    # Copy the freshly built output over the bundled pre-built CSS.
    shutil.copytree(source / "dist", root / "assets/themes/tpct-dist",
                    dirs_exist_ok=True)
    return theme_assets_present(root)


def install_themes(root: Path, *, dry_run: bool = False) -> None:
    if not theme_assets_present(root):
        if not build_theme_from_source(root):
            raise u.EngineError(
                "bundled theme CSS is missing and sassc is not installed "
                "(sudo apt install sassc)")
    themes_dir = u.data_home() / "themes"
    for variant in ("Dark", "Light"):
        dest = themes_dir / f"TPCT-Mac-{variant}"
        _install_tree(root / "assets/themes/tpct-dist" / f"TPCT-Mac-{variant}",
                      dest, dry_run=dry_run)
        if dry_run:
            continue
        liquid = (root / "assets/themes/overrides"
                  / f"liquid-{variant.lower()}.css")
        shell_css = dest / "gnome-shell/gnome-shell.css"
        if liquid.exists() and shell_css.exists():
            text = shell_css.read_text(encoding="utf-8")
            if "Generated by tools/generate_glass.py" not in text:
                shell_css.write_text(
                    text.rstrip() + "\n\n" + liquid.read_text(encoding="utf-8"),
                    encoding="utf-8")


def _write_if_changed(path: Path, text: str, *, dry_run: bool) -> None:
    if path.exists() and path.read_text(encoding="utf-8", errors="replace") == text:
        log.debug("unchanged: %s", path)
        return
    if dry_run:
        log.info("[dry-run] would write %s", path)
        return
    u.atomic_write_text(path, text)


def install_gtk_layers(root: Path, *, mode: str = "dark",
                       dry_run: bool = False) -> None:
    """GTK4/libadwaita overrides and the GTK3 user override block.

    GTK4 loads gtk.css for light and gtk-dark.css for dark, so each gets the
    matching Liquid Glass layer.  GTK3 has a single override file; the
    appearance daemon rewrites its managed block when the mode changes.
    """
    dist = root / "assets/themes/tpct-dist"
    base = (dist / "gtk-4.0/gtk-dark.css").read_text(encoding="utf-8")
    gtk_dir = root / "assets/gtk"
    light = (gtk_dir / "liquid-gtk-light.css").read_text(encoding="utf-8")
    dark = (gtk_dir / "liquid-gtk-dark.css").read_text(encoding="utf-8")
    # libadwaita loads the user gtk.css in both modes and switches with a media
    # query, so both layers live in one stylesheet.
    combined = (f"{GTK_MARKER}\n{base}\n\n{light}\n\n"
                "@media (prefers-color-scheme: dark) {\n" + dark + "\n}\n")
    config = u.config_home() / "gtk-4.0"
    _write_if_changed(config / "gtk.css", combined, dry_run=dry_run)
    _write_if_changed(config / "gtk-dark.css", combined, dry_run=dry_run)

    gtk3 = u.config_home() / "gtk-3.0/gtk.css"
    block = (root / "assets/themes/tpct-src/src/gtk3/user-overrides.css").read_text(
        encoding="utf-8").strip()
    # The upstream file carries its own marker comments; strip them so our
    # wrapper remains the single source of truth for the managed block.
    block = (block.replace("/* tpct-mac-theme: begin */", "")
                  .replace("/* tpct-mac-theme: end */", "").strip())
    liquid3 = (gtk_dir / f"liquid-gtk-{mode}.css").read_text(encoding="utf-8")
    existing = gtk3.read_text(encoding="utf-8") if gtk3.exists() else ""
    import re
    cleaned = re.sub(r"/\* macos-tahoe-ubuntu: begin \*/.*?/\* macos-tahoe-ubuntu: end \*/\n?",
                     "", existing, flags=re.S)
    new_text = (cleaned.rstrip() + "\n\n" + f"{GTK3_BEGIN}\n{block}\n\n"
                + liquid3 + f"\n{GTK3_END}\n")
    _write_if_changed(gtk3, new_text, dry_run=dry_run)


def install_icons(root: Path, *, dry_run: bool = False) -> None:
    dest = u.data_home() / "icons"
    for variant, archive_name in (("WhiteSur-dark", "WhiteSur-dark.tar.gz"),
                                  ("WhiteSur-light", "WhiteSur-light.tar.gz")):
        archive = root / "assets/icons" / archive_name
        if not archive.exists():
            raise u.EngineError(f"bundled icon archive missing: {archive}")
        if dry_run:
            log.info("[dry-run] would extract %s -> %s", archive, dest / variant)
            continue
        with tempfile.TemporaryDirectory(prefix="tahoe-icons-") as tmp:
            u.safe_extract_tar(archive, Path(tmp))
            source = Path(tmp) / variant
            if not source.exists():
                raise u.IntegrityError(f"{archive} does not contain {variant}/")
            u.copy_tree_atomic(source, dest / variant)
        cache = shutil.which("gtk-update-icon-cache")
        if cache:
            u.run([cache, "-f", "-t", str(dest / variant)], check=False, timeout=120)


def install_cursors(root: Path, *, dry_run: bool = False) -> None:
    source = root / "assets/cursors/WhiteSur-cursors"
    if not source.exists():
        raise u.EngineError(f"bundled cursors missing: {source}")
    _install_tree(source, u.data_home() / "icons/WhiteSur-cursors",
                  dry_run=dry_run)


def install_fonts(root: Path, *, dry_run: bool = False) -> None:
    font = root / "assets/fonts/Inter-Variable.ttf"
    if not font.exists():
        raise u.EngineError(f"bundled font missing: {font}")
    dest_dir = u.data_home() / "fonts"
    dest = dest_dir / font.name
    if dry_run:
        log.info("[dry-run] would install font %s", dest)
        return
    if dest.exists() and u.sha256_file(dest) == u.sha256_file(font):
        return
    dest_dir.mkdir(parents=True, exist_ok=True)
    shutil.copy2(font, dest)
    if shutil.which("fc-cache"):
        u.run(["fc-cache", "-f", str(dest_dir)], check=False, timeout=120)


def install_wallpapers(root: Path, *, dry_run: bool = False) -> Path:
    """Install the Tahoe wallpapers (Apple originals when available).

    Falls back to the project's original generated artwork if the proprietary
    Apple images are absent (e.g. an offline release without them).
    """
    dest = u.data_home() / "backgrounds/macos-tahoe"
    if not dry_run:
        dest.mkdir(parents=True, exist_ok=True)
    apple = root / "assets/wallpapers/apple"
    fallback = root / "assets/wallpapers/fallback"
    for mode in ("light", "dark"):
        name = f"tahoe-{mode}.jpg"
        source = apple / name
        if not source.exists():
            source = fallback / name
            log.info("Apple wallpaper %s unavailable; using generated fallback", name)
        if not source.exists():
            raise u.EngineError(f"no wallpaper available for {mode}")
        target = dest / name
        if dry_run:
            log.info("[dry-run] would install wallpaper %s", target)
            continue
        _install_wallpaper_file(source, target)
    return dest


def _install_wallpaper_file(source: Path, target: Path) -> None:
    """Copy, downscaling huge Apple originals for the Intel GPU.

    A 6016x6016 JPEG exceeds what this compositor renders reliably (and costs
    GPU memory), so anything above 3200 px on the long edge is resized to
    2560x2560 with ImageMagick.  A sidecar hash keeps repeated installs cheap.
    """
    source_hash = u.sha256_file(source)
    sidecar = target.with_suffix(target.suffix + ".source-sha256")
    if (target.exists() and sidecar.exists()
            and sidecar.read_text(encoding="utf-8").strip() == source_hash):
        return
    convert = shutil.which("magick") or shutil.which("convert")
    long_edge = 0
    identify = shutil.which("identify")
    if identify:
        proc = u.run([identify, "-format", "%w %h", str(source)],
                     check=False, timeout=60)
        try:
            long_edge = max(int(v) for v in (proc.stdout or "").split())
        except ValueError:
            long_edge = 0
    target.parent.mkdir(parents=True, exist_ok=True)
    if convert and long_edge > 3200:
        proc = u.run([convert, str(source), "-resize", "2560x2560",
                      "-quality", "92", str(target)], check=False, timeout=180)
        if proc.returncode != 0:
            log.warning("wallpaper downscale failed; copying original")
            shutil.copy2(source, target)
    else:
        shutil.copy2(source, target)
    sidecar.write_text(source_hash + "\n", encoding="utf-8")
    log.info("installed wallpaper %s (%s)", target.name,
             "downscaled" if long_edge > 3200 else "original")


def install_rofi_theme(root: Path, *, dry_run: bool = False) -> None:
    """Install the palette-derived Spotlight themes."""
    rofi_dir = u.config_home() / "rofi"
    for name in ("tahoe-dark.rasi", "tahoe-light.rasi"):
        source = root / "assets/rofi" / name
        if not source.exists():
            raise u.EngineError(f"generated Spotlight theme missing: {source}")
        _write_if_changed(rofi_dir / name, source.read_text(encoding="utf-8"),
                          dry_run=dry_run)


def install_spotlight_wrapper(root: Path, rofi_binary: Path | None,
                              *, dry_run: bool = False) -> Path | None:
    """Create ~/.local/bin/tahoe-spotlight (theme follows the colour scheme)."""
    wrapper = _home() / ".local/bin/tahoe-spotlight"
    themes = u.config_home() / "rofi"
    if rofi_binary is None:
        return None
    libdir = root / "runtime/rofi/usr/lib/x86_64-linux-gnu"
    ld = ""
    if (root / "runtime/rofi/usr/bin/rofi").exists():
        ld = f'export LD_LIBRARY_PATH="{libdir}${{LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}}"\n'
    script = f"""#!/bin/sh
# Generated by macos-tahoe-ubuntu: Spotlight search (Super+Space).
# GNOME/Mutter does not implement wlr-layer-shell, so rofi uses XWayland.
unset WAYLAND_DISPLAY
export GDK_BACKEND=x11
{ld}scheme=$(gsettings get org.gnome.desktop.interface color-scheme 2>/dev/null || true)
case "$scheme" in
    *light*) theme="$HOME/.config/rofi/tahoe-light.rasi" ;;
    *) theme="$HOME/.config/rofi/tahoe-dark.rasi" ;;
esac
exec "{rofi_binary}" -show drun -show-icons -display-drun "" -theme "$theme" "$@"
"""
    if dry_run:
        log.info("[dry-run] would write Spotlight wrapper %s", wrapper)
        return wrapper
    u.atomic_write_text(wrapper, script, mode=0o755)
    return wrapper


def install_firefox(root: Path, *, dry_run: bool = False) -> int:
    """Apply the Safari-style userChrome to every existing Firefox profile."""
    source = root / "assets/themes/tpct-src/firefox/userChrome.css"
    if not source.exists():
        log.warning("Firefox userChrome asset missing; skipping")
        return 0
    home = _home()
    roots = [home / "snap/firefox/common/.mozilla/firefox",
             home / ".mozilla/firefox"]
    profiles: list[Path] = []
    for base in roots:
        if base.is_dir():
            profiles.extend(p.parent for p in base.glob("*/prefs.js"))
    if not profiles:
        log.info("no Firefox profile found; skipping Safari-style userChrome")
        return 0
    for profile in profiles:
        chrome = profile / "chrome"
        target = chrome / "userChrome.css"
        if target.exists() and u.sha256_file(target) == u.sha256_file(source):
            pass
        elif dry_run:
            log.info("[dry-run] would theme Firefox profile %s", profile.name)
            continue
        else:
            chrome.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, target)
        user_js = profile / "user.js"
        if dry_run:
            continue
        text = user_js.read_text(encoding="utf-8") if user_js.exists() else ""
        if FIREFOX_MARK not in text:
            with user_js.open("a", encoding="utf-8") as fh:
                if text and not text.endswith("\n"):
                    fh.write("\n")
                fh.write(f"{FIREFOX_MARK}\n")
                fh.write('user_pref("toolkit.legacyUserProfileCustomizations.stylesheets", true);\n')
                fh.write('user_pref("browser.tabs.inTitlebar", 1);\n')
        log.info("themed Firefox profile: %s", profile.name)
    return len(profiles)


def install_ptyxis_palette(root: Path, *, dry_run: bool = False) -> bool:
    if not u.gsettings_schema_exists("org.gnome.Ptyxis"):
        return False
    source = root / "assets/themes/tpct-src/ptyxis/macOS.palette"
    if not source.exists():
        return False
    dest = u.data_home() / "org.gnome.Ptyxis/palettes"
    if dry_run:
        log.info("[dry-run] would install Ptyxis palette")
        return True
    dest.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, dest / source.name)
    return True


def install_appearance_runtime(root: Path, *, mode: str,
                               dry_run: bool = False) -> Path:
    """Install the mode-switch daemon and its palette-derived runtime assets."""
    runtime = u.data_home() / "macos-tahoe-ubuntu/appearance"
    if dry_run:
        log.info("[dry-run] would install appearance runtime in %s", runtime)
        return runtime
    runtime.mkdir(parents=True, exist_ok=True)
    for mode_name in ("light", "dark"):
        pal = u.read_json(root / f"config/palette-{mode_name}.json")
        for source in (
            root / f"config/palette-{mode_name}.json",
            root / "assets/gtk" / f"liquid-gtk-{mode_name}.css",
            root / "assets/dock" / f"liquid-dock-{mode_name}.css",
            root / "assets/themes/overrides" / f"liquid-{mode_name}.css",
            root / "assets/rofi" / f"tahoe-{mode_name}.rasi",
        ):
            if source.exists():
                shutil.copy2(source, runtime / source.name)
        if mode_name == "dark":
            pal["colors"]["surface"]

    profiles = u.read_json(root / "config/appearance-profiles.json")["modes"]
    spec = {"schema_version": 1, "modes": {}}
    for mode_name in ("light", "dark"):
        pal = u.read_json(root / f"config/palette-{mode_name}.json")
        spec["modes"][mode_name] = {
            "gtk_theme": profiles[mode_name]["gtk_theme"],
            "shell_theme": profiles[mode_name]["shell_theme"],
            "icon_theme": profiles[mode_name]["icon_theme"],
            "wallpaper": profiles[mode_name]["wallpaper"],
            "gtk3_css": f"liquid-gtk-{mode_name}.css",
            "dock_css": f"liquid-dock-{mode_name}.css",
            "dock_color": pal["colors"]["background_top"],
            "dock_opacity": 26 if mode_name == "dark" else 30,
            "blur": {
                "brightness": 0.72 if mode_name == "dark" else 0.86,
                "sigma_panel": pal["materials"]["panel"]["blur_sigma"],
                "sigma_popup": pal["materials"]["popover"]["blur_sigma"],
            },
        }
    u.atomic_write_json(runtime / "appearance.json", spec)

    binary = Path.home() / ".local/bin/tahoe-appearance-follow"
    source = root / "engine/appearance_follow.py"
    u.atomic_write_text(binary, source.read_text(encoding="utf-8"), mode=0o755)

    autostart = u.config_home() / "autostart/tahoe-appearance.desktop"
    desktop = (
        "[Desktop Entry]\n"
        "Type=Application\n"
        "Name=Tahoe Appearance\n"
        "Comment=Keep the macOS Tahoe theme in sync with Light/Dark mode\n"
        f"Exec={binary}\n"
        "Terminal=false\n"
        "NoDisplay=true\n"
        "X-GNOME-Autostart-enabled=true\n"
    )
    _write_if_changed(autostart, desktop, dry_run=False)
    log.info("appearance runtime installed (%s)", runtime)
    return runtime
