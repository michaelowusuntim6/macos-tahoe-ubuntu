"""Verify the installed desktop by inspecting files, settings and live state."""
from __future__ import annotations

import logging
import os
import shutil
from dataclasses import asdict, dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Any

from . import extension_manager, utilities as u
from .state_manager import State

log = logging.getLogger("engine")

DASH = "org.gnome.shell.extensions.dash-to-dock"
USER_THEME = "org.gnome.shell.extensions.user-theme"


@dataclass
class Check:
    id: str
    name: str
    status: str            # pass | warn | fail | skip
    detail: str = ""
    functional: bool = False


@dataclass
class Report:
    checks: list[Check] = field(default_factory=list)

    def add(self, check: Check) -> None:
        self.checks.append(check)

    @property
    def failures(self) -> list[Check]:
        return [c for c in self.checks if c.status == "fail"]

    @property
    def warnings(self) -> list[Check]:
        return [c for c in self.checks if c.status == "warn"]

    def counts(self) -> dict[str, int]:
        counts = {k: 0 for k in ("pass", "warn", "fail", "skip")}
        for check in self.checks:
            counts[check.status] = counts.get(check.status, 0) + 1
        return counts

    def ok(self) -> bool:
        return not self.failures

    def to_dict(self) -> dict:
        return {"checks": [asdict(c) for c in self.checks],
                "counts": self.counts()}


def _home(*parts: str) -> Path:
    """User binary location (conventionally ~/.local/bin)."""
    return (Path.home() / ".local/bin").joinpath(*parts) if parts and parts[0] == "tahoe-spotlight" \
        else Path.home().joinpath(*parts)


def _data(*parts: str) -> Path:
    return u.data_home().joinpath(*parts)


def _config(*parts: str) -> Path:
    return u.config_home().joinpath(*parts)


def _check_path(report: Report, ident: str, path: Path, name: str,
                kind: str = "file") -> bool:
    exists = path.is_dir() if kind == "dir" else path.is_file()
    report.add(Check(ident, name, "pass" if exists else "fail", str(path)))
    return exists


def verify_files(report: Report) -> None:
    for variant in ("Dark", "Light"):
        theme = _data("themes", f"TPCT-Mac-{variant}")
        _check_path(report, f"theme-{variant}", theme / "gnome-shell/gnome-shell.css",
                    f"Shell/GTK theme TPCT-Mac-{variant} installed", "file")
    gtk4 = _config("gtk-4.0/gtk.css")
    if gtk4.exists():
        marked = "tpct-mac-theme" in gtk4.read_text(encoding="utf-8", errors="replace")
        report.add(Check("gtk4-override", "libadwaita/GTK4 override active",
                         "pass" if marked else "fail", str(gtk4)))
    else:
        report.add(Check("gtk4-override", "libadwaita/GTK4 override active",
                         "fail", "missing"))
    gtk3 = _config("gtk-3.0/gtk.css")
    marked3 = gtk3.exists() and "macos-tahoe-ubuntu: begin" in gtk3.read_text(
        encoding="utf-8", errors="replace")
    report.add(Check("gtk3-override", "GTK3 user override active",
                     "pass" if marked3 else "fail", str(gtk3)))

    for variant in ("WhiteSur-dark", "WhiteSur-light"):
        _check_path(report, f"icons-{variant}", _data("icons", variant,
                                                     "index.theme"),
                    f"Icon theme {variant} installed", "file")
    _check_path(report, "cursors", _data("icons/WhiteSur-cursors",
                                        "cursors", "default"), "Cursor theme installed")
    _check_path(report, "font", _data("fonts/Inter-Variable.ttf"),
                "Inter font installed")
    for name in ("tahoe-dark.jpg", "tahoe-light.jpg"):
        _check_path(report, f"wallpaper-{name}",
                    _data("backgrounds/macos-tahoe", name),
                    f"Wallpaper {name} installed")
    for variant in ("Dark", "Light"):
        css = _data("themes", f"TPCT-Mac-{variant}", "gnome-shell/gnome-shell.css")
        has_glass = False
        if css.exists():
            has_glass = "Generated by tools/generate_glass.py" in css.read_text(
                encoding="utf-8", errors="replace")
        report.add(Check(f"liquid-shell-{variant}", f"Liquid Glass shell layer ({variant})",
                         "pass" if has_glass else "fail", str(css)))
    gtk4 = _config("gtk-4.0/gtk.css")
    gtk4_text = gtk4.read_text(encoding="utf-8", errors="replace") if gtk4.exists() else ""
    report.add(Check("liquid-gtk4", "GTK4 glass + dark media query",
                     "pass" if "prefers-color-scheme: dark" in gtk4_text
                     and "generate_glass.py" in gtk4_text else "fail"))
    runtime = _data("macos-tahoe-ubuntu/appearance")
    report.add(Check("appearance-runtime", "Light/Dark appearance runtime installed",
                     "pass" if (runtime / "appearance.json").exists() else "fail",
                     str(runtime)))
    autostart = _config("autostart/tahoe-appearance.desktop")
    report.add(Check("appearance-autostart", "Appearance daemon autostart",
                     "pass" if autostart.exists() else "fail", str(autostart)))


def verify_settings(report: Report, root: Path) -> None:
    desktop = u.read_json(root / "config/desktop.json")
    appearance = u.read_json(root / "config/appearance-profiles.json")

    # Only the currently active mode can be asserted live; both files are
    # checked by verify_files().
    current_scheme = u.gsettings_get("org.gnome.desktop.interface", "color-scheme")
    mode = "light" if current_scheme and "light" in current_scheme else "dark"
    active = appearance["modes"][mode]

    expected = {
        ("org.gnome.desktop.interface", "gtk-theme"): active["gtk_theme"],
        ("org.gnome.desktop.interface", "icon-theme"): active["icon_theme"],
        ("org.gnome.desktop.interface", "cursor-theme"): desktop["appearance"]["cursor_theme"],
        ("org.gnome.desktop.wm.preferences", "button-layout"): "close,minimize,maximize:",
        ("org.gnome.desktop.interface", "color-scheme"): active["color_scheme"],
    }
    for (schema, key), value in expected.items():
        actual = u.gsettings_get(schema, key)
        ok = actual == u.to_gvariant(value)
        report.add(Check(f"setting-{schema.split('.')[-1]}-{key}",
                         f"{key} = {value}", "pass" if ok else "fail",
                         f"current: {actual}"))

    shell_name = u.gsettings_get(USER_THEME, "name", u.settings_schemadir(USER_THEME))
    report.add(Check("shell-theme", f"Shell theme = {active['shell_theme']}",
                     "pass" if shell_name == u.to_gvariant(active["shell_theme"]) else "fail",
                     f"current: {shell_name}"))

    wall_light = u.gsettings_get("org.gnome.desktop.background", "picture-uri")
    wall_dark = u.gsettings_get("org.gnome.desktop.background", "picture-uri-dark")
    expects_light = "tahoe-light.jpg"
    expects_dark = "tahoe-dark.jpg"
    ok = expects_light in (wall_light or "") and expects_dark in (wall_dark or "")
    report.add(Check("wallpaper", "Light/dark Tahoe wallpapers configured",
                     "pass" if ok else "fail", f"{wall_light} | {wall_dark}"))

    font = u.gsettings_get("org.gnome.desktop.interface", "font-name") or ""
    report.add(Check("font-name", "UI font configured",
                     "pass" if "Inter" in font or "Ubuntu Sans" in font else "warn",
                     font))

    for key, value in desktop["dock"]["settings"].items():
        if key in ("background-opacity",):
            continue
        actual = u.gsettings_get(DASH, key)
        if actual is None:
            report.add(Check(f"dock-{key}", f"Dock setting {key}", "fail", "schema/key missing"))
            continue
        ok = actual == u.to_gvariant(value)
        report.add(Check(f"dock-{key}", f"Dock setting {key}",
                         "pass" if ok else "fail", f"current: {actual} expected: {u.to_gvariant(value)}"))
    try:
        opacity = float((u.gsettings_get(DASH, "background-opacity") or "1").strip("'\""))
        report.add(Check("dock-opacity", "Dock translucency applied",
                         "pass" if opacity <= 0.5 else "warn", f"opacity={opacity}"))
    except ValueError:
        report.add(Check("dock-opacity", "Dock translucency applied", "warn", "unreadable"))

    macos_schema = "org.gnome.shell.extensions.macosdock"
    macos_dir = u.settings_schemadir(macos_schema)
    if macos_dir:
        for key, expected in (("dock-position", 0), ("magnification-enabled", True),
                              ("dock-blur-enabled", True),
                              ("magnification-spring-stiffness", 320.0),
                              ("magnification-spring-damping", 26.0),
                              ("magnification-spring-mass", 1.0),
                              ("auto-hide", True),
                              ("auto-hide-delay", 550)):
            actual = u.gsettings_get(macos_schema, key, macos_dir)
            report.add(Check(f"macos-dock-{key}", f"MacOSDock {key}",
                             "pass" if actual == u.to_gvariant(expected) else "fail",
                             f"current: {actual}"))
        css = u.gsettings_get(macos_schema, "custom-css", macos_dir) or ""
        report.add(Check("macos-dock-glass", "MacOSDock Liquid Glass stylesheet",
                         "pass" if "macos-dock-container" in css else "fail",
                         f"{len(css)} chars"))
        scale = u.gsettings_get(macos_schema, "magnification-scale", macos_dir)
        report.add(Check("macos-dock-magnification", "Dock magnification configured",
                         "pass" if scale else "fail", f"scale={scale}"))
    bms_dir = u.settings_schemadir("org.gnome.shell.extensions.blur-my-shell.panel")
    if bms_dir:
        blur = u.gsettings_get("org.gnome.shell.extensions.blur-my-shell.panel",
                               "blur", bms_dir)
        sigma = u.gsettings_get("org.gnome.shell.extensions.blur-my-shell.panel",
                                "sigma", bms_dir)
        report.add(Check("bms-panel", "Panel backdrop blur active",
                         "pass" if blur == "true" else "fail",
                         f"blur={blur} sigma={sigma}"))
        static = u.gsettings_get("org.gnome.shell.extensions.blur-my-shell.panel",
                                 "static-blur", bms_dir)
        report.add(Check("bms-static", "Panel blur cached for performance",
                         "pass" if static == "true" else "warn", f"static={static}"))
    proc = u.run(["pgrep", "-f", "tahoe-appearance-follow"], check=False, timeout=10)
    report.add(Check("appearance-daemon", "Appearance daemon running",
                     "pass" if proc.returncode == 0 else "warn",
                     "process observed" if proc.returncode == 0 else
                     "starts at next login"))
    report.add(Check("light-dark", "Light and dark variants available",
                     "pass" if all((_data("themes", f"TPCT-Mac-{v}").exists())
                                   for v in ("Dark", "Light")) else "fail"))


def verify_extensions(report: Report, root: Path, system: dict) -> None:
    desktop = u.read_json(root / "config/desktop.json")
    enabled = u.gsettings_array(u.gsettings_get("org.gnome.shell", "enabled-extensions"))
    major = system["desktop"].get("gnome_major")

    for uuid in desktop["extensions"]["required"]:
        path = _data("gnome-shell/extensions", uuid)
        report.add(Check(f"ext-installed-{uuid}", f"Extension {uuid} installed",
                         "pass" if path.is_dir() else "fail", str(path)))
        meta = extension_manager.metadata(uuid)
        if meta:
            supported = str(major) in [str(v) for v in meta.get("shell-version", [])]
            report.add(Check(f"ext-compat-{uuid}",
                             f"Extension {uuid} declares GNOME {major}",
                             "pass" if supported else "fail",
                             f"shell-version={meta.get('shell-version')}"))
        report.add(Check(f"ext-enabled-{uuid}", f"Extension {uuid} enabled",
                         "pass" if uuid in enabled else "fail"))
        state = extension_manager.shell_state(uuid)
        if state is None:
            report.add(Check(f"ext-active-{uuid}", f"Extension {uuid} loaded",
                             "warn", "GNOME Shell is not running; log out and back in"))
        elif state.upper() == "ACTIVE":
            report.add(Check(f"ext-active-{uuid}", f"Extension {uuid} active",
                             "pass", state, functional=False))
        else:
            report.add(Check(f"ext-active-{uuid}", f"Extension {uuid} loaded",
                             "warn", f"state={state}; log out and back in to activate",
                             functional=False))

    # Exactly one dock implementation: MacOSDock replaced Ubuntu Dock.
    active_docks = [uuid for uuid in desktop["extensions"]["conflicting_docks"]
                    if uuid in enabled]
    macos_dock = "macos-dock@vinnytherobot.github.io" in enabled
    ubuntu_dock = "ubuntu-dock@ubuntu.com" in enabled
    disabled = u.gsettings_array(u.gsettings_get("org.gnome.shell",
                                                 "disabled-extensions"))
    ubuntu_blacklisted = "ubuntu-dock@ubuntu.com" in disabled
    ubuntu_state = extension_manager.shell_state("ubuntu-dock@ubuntu.com")
    ubuntu_loaded = ubuntu_state == "ACTIVE"
    configured_single = (macos_dock and not ubuntu_dock and ubuntu_blacklisted
                         and not active_docks)
    if configured_single and ubuntu_loaded:
        status = "warn"
        detail = ("Ubuntu Dock is blacklisted but still loaded in this session; "
                  "it unloads at next login")
    elif configured_single:
        status = "pass"
        detail = "MacOSDock only; Ubuntu Dock blacklisted and not loaded"
    else:
        status = "fail"
        detail = (f"macos-dock={macos_dock}, ubuntu-dock-in-enabled={ubuntu_dock}, "
                  f"ubuntu-blacklisted={ubuntu_blacklisted}, "
                  f"ubuntu-state={ubuntu_state}, conflicts={active_docks}")
    report.add(Check("dock-single", "Exactly one dock implementation",
                     status, detail))
    bms = "blur-my-shell@aunetx" in enabled
    report.add(Check("blur-shell", "Real backdrop blur enabled",
                     "pass" if bms else "fail", f"blur-my-shell={bms}"))


def verify_preserved(report: Report, root: Path, system: dict) -> None:
    desktop = u.read_json(root / "config/desktop.json")
    enabled = u.gsettings_array(u.gsettings_get("org.gnome.shell", "enabled-extensions"))
    originally_enabled = system["extensions"]["enabled"]
    ensure = set(desktop["extensions"].get("ensure_enabled", []))
    for uuid in desktop["extensions"]["preserve"]:
        if uuid in ensure:
            report.add(Check(f"preserve-{uuid}", f"Preserved: {uuid}",
                             "pass" if uuid in enabled else "fail",
                             "required functionality"))
            continue
        if uuid not in originally_enabled:
            report.add(Check(f"preserve-{uuid}", f"Preserved: {uuid}", "skip",
                             "was not enabled at audit time"))
            continue
        report.add(Check(f"preserve-{uuid}", f"Preserved: {uuid}",
                         "pass" if uuid in enabled else "fail",
                         "still enabled" if uuid in enabled else "was disabled"))


def verify_spotlight(report: Report, root: Path) -> Path | None:
    wrapper = _home(".local/bin/tahoe-spotlight")
    binary = shutil.which("rofi") or root / "runtime/rofi/usr/bin/rofi"
    binary_ok = Path(binary).exists() if binary else False
    report.add(Check("spotlight-binary", "Spotlight backend present",
                     "pass" if binary_ok else "fail", str(binary)))
    executable = wrapper.exists() and os.access(wrapper, os.X_OK)
    report.add(Check("spotlight-wrapper", "Spotlight launcher installed",
                     "pass" if executable else "fail", str(wrapper)))
    raw = u.gsettings_get("org.gnome.settings-daemon.plugins.media-keys",
                          "custom-keybindings")
    schema = ("org.gnome.settings-daemon.plugins.media-keys.custom-keybinding:"
              "/org/gnome/settings-daemon/plugins/media-keys/custom-keybindings/tahoe-spotlight/")
    binding = u.gsettings_get(schema, "binding")
    command = u.gsettings_get(schema, "command")
    ok = ("tahoe-spotlight" in (raw or "") and binding == "'<Super>space'"
          and command == "'tahoe-spotlight'")
    report.add(Check("spotlight-shortcut", "Super+Space opens Spotlight",
                     "pass" if ok else "fail", f"binding={binding} command={command}"))
    return wrapper if executable else None


def verify_functional(report: Report, wrapper: Path | None,
                      *, run_launch: bool = True) -> None:
    if not run_launch or wrapper is None:
        report.add(Check("spotlight-functional", "Spotlight launches",
                         "skip", "not requested"))
        return
    try:
        proc = u.run([str(wrapper), "-help"], check=False, timeout=15,
                     env={**os.environ, "WAYLAND_DISPLAY": os.environ.get("WAYLAND_DISPLAY", "")})
        ok = proc.returncode == 0
        report.add(Check("spotlight-functional", "Spotlight backend runs",
                         "pass" if ok else "warn",
                         (proc.stdout or proc.stderr or "").strip()[:200],
                         functional=True))
    except u.CommandError as exc:
        report.add(Check("spotlight-functional", "Spotlight backend runs", "warn",
                         str(exc), functional=True))


def verify(root: Path, state: State, system: dict, *, profile: str = "full",
           run_functional: bool = True) -> Report:
    report = Report()
    verify_files(report)
    verify_settings(report, root)
    verify_extensions(report, root, system)
    verify_preserved(report, root, system)
    wrapper = verify_spotlight(report, root)
    verify_functional(report, wrapper, run_launch=run_functional)
    return report


def save_report(report: Report, path: Path, *, extra: dict | None = None) -> None:
    data = report.to_dict()
    data["generated_at"] = datetime.now().isoformat(timespec="seconds")
    if extra:
        data.update(extra)
    u.atomic_write_json(path, data)


def print_report(report: Report) -> None:
    for check in report.checks:
        if check.status == "pass" and not check.functional:
            continue
        symbol = {"pass": "✓", "warn": "!", "fail": "✗", "skip": "–"}[check.status]
        log.info("%s %s%s", symbol, check.name,
                 f" — {check.detail}" if check.detail and check.status != "pass" else "")
    counts = report.counts()
    log.info("verification: %d passed, %d warnings, %d failed, %d skipped",
             counts["pass"], counts["warn"], counts["fail"], counts["skip"])
