def main() -> int:
    out = Path(sys.argv[1] if len(sys.argv) > 1 else "assets/wallpapers")
    out.mkdir(parents=True, exist_ok=True)
    for name, palette, seed in (("tahoe-dark", DARK, 11),
                                ("tahoe-light", LIGHT, 23),
                                ("tahoe-dusk", DUSK, 37)):
        path = out / f"{name}.png"
        build(palette, seed).save(path, optimize=True)
        print(f"wrote {path} ({path.stat().st_size // 1024} KiB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
