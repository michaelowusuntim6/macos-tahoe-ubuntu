#!/usr/bin/env python3
"""Generate the original macOS Tahoe-inspired wallpapers.

The artwork is generated procedurally from gradients, soft colour blooms and
flowing translucent ribbons.  No Apple artwork is used.  Output is deterministic
for a given seed, so the bundled PNGs can be regenerated byte-for-byte.

Usage: python3 tools/make_wallpapers.py [OUTPUT_DIR]
"""
from __future__ import annotations

import math
import random
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter

W, H = 2560, 1600
SS = 2  # supersampling factor for the soft shapes


def lerp(a: float, b: float, t: float) -> float:
    return a + (b - a) * t


def gradient(width: int, height: int, top: tuple, bottom: tuple,
             angle: float = 20.0) -> Image.Image:
    """Linear gradient evaluated per row with a slight diagonal skew."""
    img = Image.new("RGB", (width, height))
    px = img.load()
    rad = math.radians(angle)
    dx, dy = math.sin(rad), math.cos(rad)
    denom = abs(dx) * width + abs(dy) * height
    for y in range(height):
        for x in range(width):
            t = (dx * x + dy * y) / denom
            t = min(1.0, max(0.0, t))
            px[x, y] = tuple(round(lerp(top[i], bottom[i], t)) for i in range(3))
    return img


def bloom(size: tuple[int, int], colour: tuple, cx: float, cy: float,
          rx: float, ry: float, alpha: int) -> Image.Image:
    """Soft radial glow on an RGBA layer."""
    layer = Image.new("RGBA", size, (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    steps = 26
    for i in range(steps, 0, -1):
        t = i / steps
        a = int(alpha * (1 - t) ** 2.1)
        if a <= 0:
            continue
        d.ellipse(
            [cx - rx * t, cy - ry * t, cx + rx * t, cy + ry * t],
            fill=colour + (a,),
        )
    return layer.filter(ImageFilter.GaussianBlur(28 * SS))


def ribbon(size: tuple[int, int], colour: tuple, y0: float, amp: float,
           freq: float, phase: float, thickness: float, alpha: int,
           slope: float, colour2: tuple | None = None,
           sheen: int = 0) -> Image.Image:
    """A long, translucent, flowing ribbon with a colour gradient along it."""
    w, h = size
    layer = Image.new("RGBA", size, (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    colour2 = colour2 or colour
    n = 300
    xs, ys = [], []
    for i in range(n + 1):
        t = i / n
        x = -0.08 * w + t * 1.16 * w
        y = (y0 * h + math.sin(t * math.pi * freq + phase) * amp * h
             + math.sin(t * math.pi * freq * 2.7 + phase * 1.7) * amp * h * 0.28
             + math.sin(t * math.pi * freq * 5.1 + phase * 0.6) * amp * h * 0.09
             + (t - 0.5) * slope * h)
        xs.append(x)
        ys.append(y)
    half = thickness * h * 0.5
    for i in range(n):
        t = i / n
        c = tuple(round(lerp(colour[k], colour2[k], t)) for k in range(3))
        d.polygon([(xs[i], ys[i] - half), (xs[i + 1], ys[i + 1] - half),
                   (xs[i + 1], ys[i + 1] + half), (xs[i], ys[i] + half)],
                  fill=c + (alpha,))
    layer = layer.filter(ImageFilter.GaussianBlur(11 * SS))
    if sheen:
        hi = Image.new("RGBA", size, (0, 0, 0, 0))
        hd = ImageDraw.Draw(hi)
        for i in range(n):
            t = i / n
            a = int(sheen * math.sin(math.pi * t) ** 1.4)
            if a <= 0:
                continue
            hd.line([(xs[i], ys[i] - half * 0.72), (xs[i + 1], ys[i + 1] - half * 0.72)],
                    fill=(255, 255, 255, a), width=max(1, int(h * 0.004)))
        layer.alpha_composite(hi.filter(ImageFilter.GaussianBlur(5 * SS)))
    return layer


def vignette(img: Image.Image, strength: float = 0.38) -> Image.Image:
    """Soften the corners with a radial falloff (centre stays untouched)."""
    w, h = img.size
    mask = Image.new("L", (w, h), 0)
    d = ImageDraw.Draw(mask)
    m = int(max(w, h) * 0.92)
    d.ellipse([w // 2 - m, h // 2 - m * 4 // 5,
               w // 2 + m, h // 2 + m * 4 // 5], fill=255)
    mask = mask.filter(ImageFilter.GaussianBlur(140))
    mask = Image.eval(mask, lambda v: int(255 * (v / 255) ** 0.55))
    black = Image.new("RGB", (w, h), (0, 0, 0))
    soft = Image.composite(img, black, mask)
    return Image.blend(img, soft, strength)


def grain(img: Image.Image, amount: int = 5, seed: int = 7) -> Image.Image:
    rnd = random.Random(seed)
    w, h = img.size
    noise = Image.new("L", (w // 2, h // 2))
    noise.putdata([128 + rnd.randint(-amount, amount) for _ in range(noise.width * noise.height)])
    noise = noise.resize((w, h), Image.BILINEAR)
    return Image.blend(img, Image.merge("RGB", (noise, noise, noise)), 0.035)


def build(palette: dict, seed: int) -> Image.Image:
    w, h = W, H
    rnd = random.Random(seed)
    canvas = gradient(w, h, palette["top"], palette["bottom"], palette.get("angle", 22))
    canvas = canvas.convert("RGBA")

    for b in palette["blooms"]:
        canvas.alpha_composite(bloom((w, h), b["c"], b["x"] * w, b["y"] * h,
                                     b["rx"] * w, b["ry"] * h, b["a"]))
    for r in palette["ribbons"]:
        canvas.alpha_composite(ribbon(
            (w, h), r["c"], r["y"], r["amp"], r["freq"], r["phase"],
            r["th"], r["a"], r.get("slope", 0),
            colour2=r.get("c2"), sheen=r.get("sheen", 0)))
    img = canvas.convert("RGB")
    img = vignette(img, palette.get("vignette", 0.30))
    img = grain(img, palette.get("grain", 5), seed)
    return img


