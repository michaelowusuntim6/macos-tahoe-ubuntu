def main() -> int:
    for mode in ("light", "dark"):
        pal = load(mode)
        outputs = {
            ASSETS / f"themes/overrides/liquid-{mode}.css": shell_css(pal),
            ASSETS / f"gtk/liquid-gtk-{mode}.css": gtk_css(pal),
            ASSETS / f"dock/liquid-dock-{mode}.css": dock_css(pal),
            ASSETS / f"rofi/tahoe-{mode}.rasi": rofi_rasi(pal),
        }
        for path, content in outputs.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
            print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
