#!/usr/bin/env python3
"""Generate the Liquid Glass CSS from the measured palettes.

Outputs (all consumed by the installer):
  assets/themes/overrides/liquid-{light,dark}.css   GNOME Shell glass layers
  assets/gtk/liquid-gtk-{light,dark}.css           GTK3/GTK4 surface layers
  assets/dock/liquid-dock-{light,dark}.css         MacOSDock glass + motion styling
  assets/rofi/tahoe-{light,dark}.rasi              Spotlight glass

The approximation is explicit: GNOME Shell gets real backdrop blur through
Blur my Shell and Shell.BlurEffect; GTK cannot blur the desktop behind a
window, so its surfaces use layered gradients, edge highlights and shadows
instead.  No proprietary Apple rendering engine is claimed.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets"


def load(mode: str) -> dict:
    return json.loads((ROOT / f"config/palette-{mode}.json").read_text())


def rgba(hex_colour: str, alpha: float) -> str:
    h = hex_colour.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
    return f"rgba({r}, {g}, {b}, {alpha:.3f})"


def mix(a: str, b: str, t: float) -> str:
    ca = [int(a.lstrip("#")[i:i + 2], 16) for i in (0, 2, 4)]
    cb = [int(b.lstrip("#")[i:i + 2], 16) for i in (0, 2, 4)]
    return "#" + "".join(f"{round(ca[i] + (cb[i] - ca[i]) * t):02x}" for i in range(3))


def luminance(hex_colour: str) -> float:
    h = hex_colour.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    def lin(c):
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b)


